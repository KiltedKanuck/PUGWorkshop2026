function Parse-K6Data {
    param([string]$FilePath)
    
    $lines = Get-Content $FilePath
    $data = @{
        Config = $null
        Params = $null
        Metrics = [ordered]@{}
        StartTime = $null
        Snapshots = @()
    }
    
    $inSnapshotPhase = $false
    $inTeardownPhase = $false
    
    foreach ($line in $lines) {
        $event = $line | ConvertFrom-Json
        
        switch ($event.event) {
            "config" { $data.Config = $event.data }
            "param" { $data.Params = $event.data }
            "metric" { 
                # Only collect metrics that appear before snapshots start
                # (setup/teardown metrics appear after snapshots and aren't in the arrays)
                if (-not $inSnapshotPhase) {
                    $event.data.PSObject.Properties | ForEach-Object {
                        if (-not $data.Metrics.Contains($_.Name)) {
                            $data.Metrics[$_.Name] = $_.Value
                        }
                    }
                } else {
                    # Second metric event means we've entered teardown phase
                    $inTeardownPhase = $true
                }
            }
            "start" { $data.StartTime = $event.data[0][0] }
            "snapshot" { 
                # Only collect snapshots from main test phase, not teardown
                if (-not $inTeardownPhase) {
                    $inSnapshotPhase = $true
                    $data.Snapshots += ,$event.data
                }
            }
        }
    }
    
    return $data
}

function Get-MetricStats {
    param(
        [array]$Snapshots,
        [System.Collections.Specialized.OrderedDictionary]$Metrics
    )
    
    # Build metric index mapping
    # The snapshot is an array where each element corresponds to one metric (in insertion order)
    # Each snapshot element is itself an array with values based on metric type
    $metricIndexMap = @{}
    $index = 0
    
    foreach ($entry in $Metrics.GetEnumerator()) {
        $metricIndexMap[$entry.Key] = $index
        $index++
    }
    
    # Validate that required metrics exist
    $requiredMetrics = @('http_req_duration', 'http_req_waiting', 'iteration_duration', 'http_reqs', 'http_req_failed', 'vus')
    foreach ($required in $requiredMetrics) {
        if (-not $metricIndexMap.ContainsKey($required)) {
            Write-Warning "Required metric '$required' not found in data. Results may be incomplete."
        }
    }
    
    # HARDCODED indices based on actual snapshot structure
    # These positions are verified against snapshot 1+ (after setup phase)
    # Note: Snapshot 0 has different structure with setup metrics populated
    $httpDurationIdx = 12
    $httpWaitingIdx = 22
    $iterationDurationIdx = 25
    $httpReqsIdx = 23  # Position 24 in setup snapshot, 23 in main test snapshots
    $httpFailedIdx = 14
    $vusIdx = 28
    
    $stats = @{
        Duration_Avg = @()
        Duration_P90 = @()
        Duration_P95 = @()
        Duration_P99 = @()
        Duration_Max = @()
        Duration_Min = @()
        Duration_Med = @()
        RequestRate = @()
        VUs = @()
        FailedRate = @()
        Waiting_Avg = @()
        Waiting_P95 = @()
        Iteration_Avg = @()
        Iteration_P95 = @()
    }
    
    foreach ($snapshot in $Snapshots) {
        # http_req_duration [avg, max, med, min, p90, p95, p99]
        if ($httpDurationIdx -ne $null -and $snapshot.Count -gt $httpDurationIdx -and $snapshot[$httpDurationIdx] -is [array] -and $snapshot[$httpDurationIdx].Count -ge 7) {
            $stats.Duration_Avg += [double]$snapshot[$httpDurationIdx][0]
            $stats.Duration_Max += [double]$snapshot[$httpDurationIdx][1]
            $stats.Duration_Med += [double]$snapshot[$httpDurationIdx][2]
            $stats.Duration_Min += [double]$snapshot[$httpDurationIdx][3]
            $stats.Duration_P90 += [double]$snapshot[$httpDurationIdx][4]
            $stats.Duration_P95 += [double]$snapshot[$httpDurationIdx][5]
            $stats.Duration_P99 += [double]$snapshot[$httpDurationIdx][6]
        }
        
        # http_req_waiting [avg, max, med, min, p90, p95, p99]
        if ($httpWaitingIdx -ne $null -and $snapshot.Count -gt $httpWaitingIdx -and $snapshot[$httpWaitingIdx] -is [array] -and $snapshot[$httpWaitingIdx].Count -ge 7) {
            $stats.Waiting_Avg += [double]$snapshot[$httpWaitingIdx][0]
            $stats.Waiting_P95 += [double]$snapshot[$httpWaitingIdx][5]
        }
        
        # iteration_duration [avg, max, med, min, p90, p95, p99]
        if ($iterationDurationIdx -ne $null -and $snapshot.Count -gt $iterationDurationIdx -and $snapshot[$iterationDurationIdx] -is [array] -and $snapshot[$iterationDurationIdx].Count -ge 7) {
            $stats.Iteration_Avg += [double]$snapshot[$iterationDurationIdx][0]
            $stats.Iteration_P95 += [double]$snapshot[$iterationDurationIdx][5]
        }
        
        # VUs - single value
        if ($vusIdx -ne $null -and $snapshot.Count -gt $vusIdx -and $snapshot[$vusIdx]) {
            $vu = if ($snapshot[$vusIdx] -is [array]) { $snapshot[$vusIdx][0] } else { $snapshot[$vusIdx] }
            $stats.VUs += [double]$vu
        }
        
        # Failed rate - single value
        if ($httpFailedIdx -ne $null -and $snapshot.Count -gt $httpFailedIdx -and $snapshot[$httpFailedIdx]) {
            $failed = if ($snapshot[$httpFailedIdx] -is [array]) { $snapshot[$httpFailedIdx][0] } else { $snapshot[$httpFailedIdx] }
            $stats.FailedRate += [double]$failed
        }
        
        # Request rate - from http_reqs [count, rate]
        if ($httpReqsIdx -ne $null -and $snapshot.Count -gt $httpReqsIdx -and $snapshot[$httpReqsIdx] -is [array] -and $snapshot[$httpReqsIdx].Count -gt 1) {
            $stats.RequestRate += [double]$snapshot[$httpReqsIdx][1]
        }
    }
    
    return $stats
}

function Calculate-Summary {
    param([array]$Values)
    
    if ($Values.Count -eq 0) {
        return @{
            Min = 0
            Max = 0
            Avg = 0
            Median = 0
            StdDev = 0
        }
    }
    
    $sorted = $Values | Sort-Object
    $avg = ($Values | Measure-Object -Average).Average
    $median = if ($sorted.Count % 2 -eq 0) {
        ($sorted[$sorted.Count/2 - 1] + $sorted[$sorted.Count/2]) / 2
    } else {
        $sorted[[math]::Floor($sorted.Count/2)]
    }
    
    $variance = ($Values | ForEach-Object { [math]::Pow($_ - $avg, 2) } | Measure-Object -Average).Average
    $stdDev = [math]::Sqrt($variance)
    
    return @{
        Min = ($sorted | Select-Object -First 1)
        Max = ($sorted | Select-Object -Last 1)
        Avg = $avg
        Median = $median
        StdDev = $stdDev
    }
}


Write-Host "`n=== Loading Test Data ===" -ForegroundColor Cyan
Write-Host "Baseline: $BaselineFile"
Write-Host "Comparison: $ComparisonFile"

$baseline = Parse-K6Data -FilePath $BaselineFile
$comparison = Parse-K6Data -FilePath $ComparisonFile

Write-Host "`nBaseline event snapshots: $($baseline.Snapshots.Count)"
Write-Host "Comparison event snapshots: $($comparison.Snapshots.Count)"

# Extract metrics
Write-Host "`n=== Extracting Metrics ===" -ForegroundColor Cyan

Write-Host "Baseline metrics found: $($baseline.Metrics.Count)"
Write-Host "Comparison metrics found: $($comparison.Metrics.Count)"
if ($baseline.Snapshots.Count -gt 0) {
    Write-Host "Baseline snapshot array length: $($baseline.Snapshots[0].Count)"
}
if ($comparison.Snapshots.Count -gt 0) {
    Write-Host "Comparison snapshot array length: $($comparison.Snapshots[0].Count)"
}

$baselineStats = Get-MetricStats -Snapshots $baseline.Snapshots -Metrics $baseline.Metrics
$comparisonStats = Get-MetricStats -Snapshots $comparison.Snapshots -Metrics $comparison.Metrics

# Calculate summaries
Write-Host "`n=== HTTP REQUEST DURATION COMPARISON (milliseconds) ===" -ForegroundColor Yellow

$metrics = @("Duration_Avg", "Duration_P90", "Duration_P95", "Duration_P99", "Duration_Max")
$results = @()

foreach ($metric in $metrics) {
    $baseSummary = Calculate-Summary -Values $baselineStats[$metric]
    $compSummary = Calculate-Summary -Values $comparisonStats[$metric]
    
    $metricName = $metric -replace "Duration_", ""
    $diff = $compSummary.Avg - $baseSummary.Avg
    $diffPct = if ($baseSummary.Avg -gt 0) { ($diff / $baseSummary.Avg) * 100 } else { 0 }
    
    $result = [PSCustomObject]@{
        Metric = $metricName
        Baseline_Avg = [math]::Round($baseSummary.Avg, 2)
        Baseline_Min = [math]::Round($baseSummary.Min, 2)
        Baseline_Max = [math]::Round($baseSummary.Max, 2)
        Comparison_Avg = [math]::Round($compSummary.Avg, 2)
        Comparison_Min = [math]::Round($compSummary.Min, 2)
        Comparison_Max = [math]::Round($compSummary.Max, 2)
        Diff_ms = [math]::Round($diff, 2)
        Diff_Percent = [math]::Round($diffPct, 2)
    }
    
    $results += $result
}

$results | Format-Table -AutoSize

# Additional metrics
Write-Host "`n=== ADDITIONAL TIMING METRICS ===" -ForegroundColor Yellow

# Waiting time (Time to First Byte)
$baseWaiting = Calculate-Summary -Values $baselineStats.Waiting_Avg
$compWaiting = Calculate-Summary -Values $comparisonStats.Waiting_Avg
$waitingDiff = $compWaiting.Avg - $baseWaiting.Avg

Write-Host "`nHTTP Waiting Time (TTFB) - Average (ms):"
Write-Host "  Baseline    : $([math]::Round($baseWaiting.Avg, 2))"
Write-Host "  Comparison  : $([math]::Round($compWaiting.Avg, 2))"
$waitingSign = if ($waitingDiff -ge 0) { "+" } else { "" }
Write-Host "  Difference  : $waitingSign$([math]::Round($waitingDiff, 2))ms" -ForegroundColor $(if ($waitingDiff -gt 1000) { "Red" } elseif ($waitingDiff -gt 500) { "Yellow" } else { "Green" })

# Iteration duration
$baseIter = Calculate-Summary -Values $baselineStats.Iteration_Avg
$compIter = Calculate-Summary -Values $comparisonStats.Iteration_Avg
$iterDiff = $compIter.Avg - $baseIter.Avg

Write-Host "`nIteration Duration - Average (ms):"
Write-Host "  Baseline    : $([math]::Round($baseIter.Avg, 2))"
Write-Host "  Comparison  : $([math]::Round($compIter.Avg, 2))"
$iterSign = if ($iterDiff -ge 0) { "+" } else { "" }
Write-Host "  Difference  : $iterSign$([math]::Round($iterDiff, 2))ms" -ForegroundColor $(if ($iterDiff -gt 2000) { "Red" } elseif ($iterDiff -gt 1000) { "Yellow" } else { "Green" })

Write-Host "`n=== OTHER METRICS ===" -ForegroundColor Yellow

$otherMetrics = @{
    "Request Rate (req/s)" = @("RequestRate", $baselineStats.RequestRate, $comparisonStats.RequestRate)
    "Virtual Users" = @("VUs", $baselineStats.VUs, $comparisonStats.VUs)
}

foreach ($key in $otherMetrics.Keys) {
    $metric = $otherMetrics[$key]
    $baseSummary = Calculate-Summary -Values $metric[1]
    $compSummary = Calculate-Summary -Values $metric[2]
    
    Write-Host "`n$key"
    Write-Host "  Baseline    : Avg=$([math]::Round($baseSummary.Avg, 2)) Min=$([math]::Round($baseSummary.Min, 2)) Max=$([math]::Round($baseSummary.Max, 2))"
    Write-Host "  Comparison  : Avg=$([math]::Round($compSummary.Avg, 2)) Min=$([math]::Round($compSummary.Min, 2)) Max=$([math]::Round($compSummary.Max, 2))"
    
    $diff = $compSummary.Avg - $baseSummary.Avg
    $diffPct = if ($baseSummary.Avg -gt 0) { ($diff / $baseSummary.Avg) * 100 } else { 0 }
    $diffSign = if ($diff -ge 0) { "+" } else { "" }
    Write-Host "  Difference  : $diffSign$([math]::Round($diff, 2)) ($diffSign$([math]::Round($diffPct, 2))%)" -ForegroundColor $(if ($diff -lt 0) { "Green" } else { "Yellow" })
}

# Test duration comparison
Write-Host "`n=== TEST DURATION ===" -ForegroundColor Yellow
$baselineDuration = ($baseline.Snapshots.Count * 30) # event snapshots every 30 seconds
$comparisonDuration = ($comparison.Snapshots.Count * 30)
Write-Host "Baseline    : $([math]::Round($baselineDuration / 60, 1)) minutes ($($baseline.Snapshots.Count) event snapshots)"
Write-Host "Comparison  : $([math]::Round($comparisonDuration / 60, 1)) minutes ($($comparison.Snapshots.Count) event snapshots)"

# Key insights
Write-Host "`n=== KEY INSIGHTS ===" -ForegroundColor Cyan

$avgDurationDiff = ($results | Where-Object { $_.Metric -eq "Avg" }).Diff_ms
$avgDurationPct = ($results | Where-Object { $_.Metric -eq "Avg" }).Diff_Percent
$avgDurationSign = if ($avgDurationDiff -ge 0) { "+" } else { "" }
$avgDurationPctSign = if ($avgDurationPct -ge 0) { "+" } else { "" }
$p95Diff = ($results | Where-Object { $_.Metric -eq "P95" }).Diff_ms
$p95DiffSign = if ($p95Diff -ge 0) { "+" } else { "" }
$p99Diff = ($results | Where-Object { $_.Metric -eq "P99" }).Diff_ms
$p99DiffSign = if ($p99Diff -ge 0) { "+" } else { "" }

Write-Host "1. Average Response Time Impact:"
Write-Host "   Comparison adds ~$avgDurationSign$([math]::Round($avgDurationDiff, 2))ms ($avgDurationPctSign$([math]::Round($avgDurationPct, 1))%)" -ForegroundColor $(if ($avgDurationDiff -gt 1000) { "Red" } elseif ($avgDurationDiff -gt 500) { "Yellow" } else { "Green" })

Write-Host "`n2. P95 Latency Impact:"
Write-Host "   Comparison adds ~$p95DiffSign$([math]::Round($p95Diff, 2))ms at 95th percentile" -ForegroundColor $(if ($p95Diff -gt 2000) { "Red" } elseif ($p95Diff -gt 1000) { "Yellow" } else { "Green" })

Write-Host "`n3. P99 Latency Impact:"
Write-Host "   Comparison adds ~$p99DiffSign$([math]::Round($p99Diff, 2))ms at 99th percentile" -ForegroundColor $(if ($p99Diff -gt 3000) { "Red" } elseif ($p99Diff -gt 1500) { "Yellow" } else { "Green" })

$baseRequestRate = (Calculate-Summary -Values $baselineStats.RequestRate).Avg
$compRequestRate = (Calculate-Summary -Values $comparisonStats.RequestRate).Avg
$throughputImpact = if ($baseRequestRate -gt 0) { 
    (($baseRequestRate - $compRequestRate) / $baseRequestRate) * 100 
} else { 
    0 
}

Write-Host "`n4. Throughput Impact:"
if ($baseRequestRate -gt 0) {
    $throughputSign = if ($throughputImpact -ge 0) { "+" } else { "" }
    Write-Host "   Comparison reduces throughput by ~$throughputSign$([math]::Round($throughputImpact, 1))%" -ForegroundColor $(if ($throughputImpact -gt 50) { "Red" } elseif ($throughputImpact -gt 25) { "Yellow" } else { "Green" })
} else {
    Write-Host "   Unable to calculate throughput impact (baseline rate = 0)" -ForegroundColor Yellow
}


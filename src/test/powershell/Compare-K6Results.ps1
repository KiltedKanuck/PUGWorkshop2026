if ($OutputReport) {
    $report = @()
    
    $report += "# k6 Results Comparison Report"
    $report += ""
    $report += "**Generated:** $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
    $report += ""
    $report += "**Baseline:** ``$BaselineFile``"
    $report += ""
    $report += "**Comparison:** ``$ComparisonFile``"
    $report += ""
    $report += "- Baseline event snapshots: $($baseline.Snapshots.Count)"
    $report += "- Comparison event snapshots: $($comparison.Snapshots.Count)"
    $report += ""
    
    $report += "## HTTP Request Duration Comparison (milliseconds)"
    $report += ""
    
    # Create markdown table
    $report += "| Metric | Baseline Avg | Baseline Min | Baseline Max | Comparison Avg | Comparison Min | Comparison Max | Diff (ms) | Diff (%) |"
    $report += "|--------|--------------|--------------|--------------|----------------|----------------|----------------|-----------|----------|"
    foreach ($result in $results) {
        $report += "| $($result.Metric) | $($result.Baseline_Avg) | $($result.Baseline_Min) | $($result.Baseline_Max) | $($result.Comparison_Avg) | $($result.Comparison_Min) | $($result.Comparison_Max) | $($result.Diff_ms) | $($result.Diff_Percent) |"
    }
    $report += ""
    
    $report += "## Additional Timing Metrics"
    $report += ""
    
    $report += "### HTTP Waiting Time (TTFB) - Average (ms)"
    $report += ""
    $report += "- **Baseline:** $([math]::Round($baseWaiting.Avg, 2))"
    $report += "- **Comparison:** $([math]::Round($compWaiting.Avg, 2))"
    $waitingSign = if ($waitingDiff -ge 0) { "+" } else { "" }
    $report += "- **Difference:** $waitingSign$([math]::Round($waitingDiff, 2))ms"
    $report += ""
    
    $report += "### Iteration Duration - Average (ms)"
    $report += ""
    $report += "- **Baseline:** $([math]::Round($baseIter.Avg, 2))"
    $report += "- **Comparison:** $([math]::Round($compIter.Avg, 2))"
    $iterSign = if ($iterDiff -ge 0) { "+" } else { "" }
    $report += "- **Difference:** $iterSign$([math]::Round($iterDiff, 2))ms"
    $report += ""
    
    $report += "## Other Metrics"
    $report += ""
    
    foreach ($key in $otherMetrics.Keys) {
        $metric = $otherMetrics[$key]
        $baseSummary = Calculate-Summary -Values $metric[1]
        $compSummary = Calculate-Summary -Values $metric[2]
        
        $report += "### $key"
        $report += ""
        $report += "- **Baseline:** Avg=$([math]::Round($baseSummary.Avg, 2)) Min=$([math]::Round($baseSummary.Min, 2)) Max=$([math]::Round($baseSummary.Max, 2))"
        $report += "- **Comparison:** Avg=$([math]::Round($compSummary.Avg, 2)) Min=$([math]::Round($compSummary.Min, 2)) Max=$([math]::Round($compSummary.Max, 2))"
        
        $diff = $compSummary.Avg - $baseSummary.Avg
        $diffPct = if ($baseSummary.Avg -gt 0) { ($diff / $baseSummary.Avg) * 100 } else { 0 }
        $diffSign = if ($diff -ge 0) { "+" } else { "" }
        $report += "- **Difference:** $diffSign$([math]::Round($diff, 2)) ($diffSign$([math]::Round($diffPct, 2))%)"
        $report += ""
    }
    
    $report += "## Test Duration"
    $report += ""
    $report += "- **Baseline:** $([math]::Round($baselineDuration / 60, 1)) minutes ($($baseline.Snapshots.Count) event snapshots)"
    $report += "- **Comparison:** $([math]::Round($comparisonDuration / 60, 1)) minutes ($($comparison.Snapshots.Count) event snapshots)"
    $report += ""
    
    $report += "## Key Insights"
    $report += ""
    
    $report += "### 1. Average Response Time Impact"
    $report += ""
    $report += "Comparison adds ~$avgDurationSign$([math]::Round($avgDurationDiff, 2))ms ($avgDurationPctSign$([math]::Round($avgDurationPct, 1))%)"
    $report += ""
    
    $report += "### 2. P95 Latency Impact"
    $report += ""
    $report += "Comparison adds ~$p95DiffSign$([math]::Round($p95Diff, 2))ms at 95th percentile"
    $report += ""
    
    $report += "### 3. P99 Latency Impact"

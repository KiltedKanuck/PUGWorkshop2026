<#
.SYNOPSIS
    Compares results of two k6 dashboard data files (as JSON) to analyze performance differences.

.DESCRIPTION
    Analyzes and compares HTTP response times, request rates, and other metrics
    between two k6 test runs to identify performance differences.
    
    This script expects dashboard-data.json files extracted from k6 HTML reports
    using Extract-K6Data.ps1. These files contain time-series metrics in NDJSON format.

.PARAMETER BaselineFile
    Path to the baseline dashboard-data.json file (e.g., Test A).
    This should be extracted using Extract-K6Data.ps1 from a k6 HTML report.

.PARAMETER ComparisonFile
    Path to the comparison dashboard-data.json file (e.g., Test B).
    This should be extracted using Extract-K6Data.ps1 from a k6 HTML report.

.PARAMETER OutputReport
    Optional path for saving the comparison report as a markdown file

.EXAMPLE
    .\Compare-K6Results.ps1 "test_a\dashboard-data.json" "test_b\dashboard-data.json"
    
.EXAMPLE
    .\Compare-K6Results.ps1 -BaselineFile "test_a-data.json" -ComparisonFile "test_b-data.json"

.EXAMPLE
    .\Compare-K6Results.ps1 -BaselineFile "test_a-data.json" -ComparisonFile "test_b-data.json" -OutputReport "comparison.md"
    
.NOTES
    Input files must be dashboard-data.json files extracted from k6 HTML reports.
    Use Extract-K6Data.ps1 to extract these files from the dashboard.html reports
    which are generated by k6 tests run with the -useDashboard option.
#>

